create table public.agents (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null check (char_length(name) between 1 and 80),
  role text not null check (role in ('admin', 'agent')),
  active boolean not null default true,
  access_configured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.activity_definitions (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label_zh text not null,
  label_en text not null,
  points integer not null check (points between 0 and 100),
  sort_order integer not null,
  active boolean not null default true
);

create table public.daily_activity (
  id bigint generated by default as identity primary key,
  agent_id bigint not null references public.agents(id) on delete cascade,
  activity_date date not null,
  completed_action_ids integer[] not null default '{}',
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  unique (agent_id, activity_date)
);

create table public.weekly_reviews (
  id bigint generated by default as identity primary key,
  agent_id bigint not null references public.agents(id) on delete cascade,
  week_start date not null,
  strongest_action text not null default '',
  biggest_gap text not null default '',
  top_prospects text not null default '',
  next_improvement text not null default '',
  next_case_target text not null default '',
  next_tpc_target text not null default '',
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  unique (agent_id, week_start)
);

create table public.agent_credentials (
  agent_id bigint primary key references public.agents(id) on delete cascade,
  salt text not null,
  code_hash text not null,
  algorithm text not null default 'pbkdf2-sha256' check (algorithm = 'pbkdf2-sha256'),
  iterations integer not null default 120000 check (iterations between 100000 and 1000000),
  updated_at timestamptz not null default now()
);

create table public.scoreboard_login_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  agent_id bigint not null references public.agents(id) on delete cascade,
  attempted_at timestamptz not null default now()
);

create index daily_activity_agent_date_idx on public.daily_activity (agent_id, activity_date);
create index weekly_reviews_agent_week_idx on public.weekly_reviews (agent_id, week_start);
create index agents_active_role_idx on public.agents (active, role, code);
create index scoreboard_login_attempts_lookup_idx
  on public.scoreboard_login_attempts (user_id, agent_id, attempted_at desc);

create or replace function private.current_agent_id()
returns bigint
language sql
stable
set search_path = ''
as $$
  select nullif(auth.jwt() -> 'app_metadata' ->> 'scoreboard_agent_id', '')::bigint
$$;

create or replace function private.current_scoreboard_role()
returns text
language sql
stable
set search_path = ''
as $$
  select auth.jwt() -> 'app_metadata' ->> 'scoreboard_role'
$$;

create or replace function private.is_scoreboard_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    (select private.current_scoreboard_role()) = 'admin'
    and exists (
      select 1
      from public.agents
      where id = (select private.current_agent_id())
        and role = 'admin'
        and active
    )
$$;

create or replace function private.can_access_scoreboard_agent(target_agent_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    (select private.is_scoreboard_admin())
    or exists (
      select 1
      from public.agents
      where id = (select private.current_agent_id())
        and id = target_agent_id
        and role = 'agent'
        and active
        and (select private.current_scoreboard_role()) = 'agent'
    )
$$;

revoke all on function private.current_agent_id() from public;
