create policy "signed in users can read the agent roster"
on public.agents for select
to authenticated
using (true);

create policy "admins can insert agents"
on public.agents for insert
to authenticated
with check ((select private.is_scoreboard_admin()));

create policy "admins can update agents"
on public.agents for update
to authenticated
using ((select private.is_scoreboard_admin()))
with check ((select private.is_scoreboard_admin()));

create policy "admins can delete agents"
on public.agents for delete
to authenticated
using ((select private.is_scoreboard_admin()));

create policy "signed in users can read active definitions"
on public.activity_definitions for select
to authenticated
using (active or (select private.is_scoreboard_admin()));

